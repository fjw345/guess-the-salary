export function tagsForSchool(name: string, region: string): string[] {
  const classifiedName = classificationParent[name] ?? name;
  const tags: DomesticSchoolTag[] = [];
  if (c9Schools.has(classifiedName)) tags.push('C9');
  if (project985Schools.has(classifiedName)) tags.push('985');
  if (project211Schools.has(classifiedName)) tags.push('211');
  if (doubleFirstClassSchools.has(classifiedName)) tags.push('双一流');
  return [...tags, levelForSchool(name), region];
}

export function levelForSchool(name: string): SchoolLevelTag {
  if (undergraduateVocationalSchools.has(name)) return '本科';
  return juniorCollegeName.test(name) ? '专科' : '本科';
}

